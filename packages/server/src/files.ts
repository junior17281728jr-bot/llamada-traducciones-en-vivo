import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

/** Writes `contents` atomically (temp file + rename) with owner-only permissions. */
export async function writePrivateFile(path: string, contents: string | Uint8Array): Promise<void> {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  const temp = `${path}.${randomBytes(6).toString('hex')}.tmp`;
  await writeFile(temp, contents, { mode: 0o600 });
  await rename(temp, path);
}

export async function readJsonFile<T>(path: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(path, 'utf8')) as T;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw error;
  }
}

/** Call ids are generated by the server; anything else must never reach a file path. */
export const SAFE_ID = /^[A-Za-z0-9_-]{1,128}$/;

export function assertSafeId(id: string): void {
  if (!SAFE_ID.test(id)) throw new Error('Identificador no válido');
}
